import { readFile, writeFile } from 'node:fs/promises';

const source = await readFile(new URL('../client/notebook.js', import.meta.url), 'utf8');
const sidebar = await readFile(new URL('../client/sidebar.js', import.meta.url), 'utf8');
const memory = await readFile(new URL('../client/memory.js', import.meta.url), 'utf8');
const study = await readFile(new URL('../client/study.js', import.meta.url), 'utf8');
const css = (await Promise.all(['notebook', 'study', 'study-learn', 'study-gemini', 'study-chat'].map((name) =>
  readFile(new URL(`../client/${name}.css`, import.meta.url), 'utf8')))).join('\n');
const sidebarCss = await readFile(new URL('../client/sidebar.css', import.meta.url), 'utf8');
const manifest = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const bundle = `// Generated by scripts/build.mjs.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory(require) {
    const React = require('react');
    const { createPortal } = require('react-dom');
    const stylesheet = ${JSON.stringify(css)};
    const sidebarStylesheet = ${JSON.stringify(sidebarCss)};
    ${source.trimEnd()}
    ${sidebar.trimEnd()}
    ${memory.trimEnd()}
    ${study.trimEnd()}
    return { apply, inject };
  },
});
`;
await writeFile(new URL('../lib/client.js', import.meta.url), bundle);
